//go:build ignore

// gen_rpcproto writes rpcproto_gen.go: the RPC protocol version of the
// llama.cpp pinned in ../LLAMA_CPP_VERSION, read from that tag's
// ggml/include/ggml-rpc.h. Run via `go generate ./cluster` (needs network).
// -header reads a local copy of the header instead of fetching it.
package main

import (
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"regexp"
	"strings"
)

func main() {
	header := flag.String("header", "", "local ggml-rpc.h to read instead of fetching")
	flag.Parse()

	tagBytes, err := os.ReadFile("../LLAMA_CPP_VERSION")
	if err != nil {
		log.Fatal(err)
	}
	tag := strings.TrimSpace(string(tagBytes))

	var src []byte
	if *header != "" {
		src, err = os.ReadFile(*header)
	} else {
		src, err = fetch("https://raw.githubusercontent.com/ggml-org/llama.cpp/" + tag + "/ggml/include/ggml-rpc.h")
	}
	if err != nil {
		log.Fatal(err)
	}

	major, minor := define(src, "MAJOR"), define(src, "MINOR")
	out, err := format.Source([]byte(fmt.Sprintf(`// Code generated by gen_rpcproto.go; DO NOT EDIT.

package cluster

// RPCLlamaCppTag is the LLAMA_CPP_VERSION these values were read from;
// TestRPCProtoMatchesPin fails if the pin moves without regenerating.
//
// RPCProtoMajor/RPCProtoMinor are RPC_PROTO_MAJOR_VERSION/
// RPC_PROTO_MINOR_VERSION from ggml/include/ggml-rpc.h at that tag. Peers
// advertise them and placement only pairs peers whose major matches and whose
// minor is no higher than ours.
const (
	RPCLlamaCppTag = %q
	RPCProtoMajor  = %s
	RPCProtoMinor  = %s
)
`, tag, major, minor)))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("rpcproto_gen.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}

func fetch(url string) ([]byte, error) {
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

func define(src []byte, which string) string {
	m := regexp.MustCompile(`(?m)^#define\s+RPC_PROTO_` + which + `_VERSION\s+(\d+)\s*$`).FindSubmatch(src)
	if m == nil {
		log.Fatalf("RPC_PROTO_%s_VERSION not found in ggml-rpc.h", which)
	}
	return string(m[1])
}
